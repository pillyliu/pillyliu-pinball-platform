function report_ip_in_any_cidr(string $ip, array $cidrs): bool
{
    foreach ($cidrs as $cidr) {
        if (is_string($cidr) && report_ip_in_cidr($ip, $cidr)) {
            return true;
        }
    }
    return false;
}

function report_ip_in_cidr(string $ip, string $cidr): bool
{
    [$network, $prefixText] = array_pad(explode('/', $cidr, 2), 2, null);
    if ($prefixText === null || !ctype_digit($prefixText)) {
        return false;
    }
    $ipBytes = @inet_pton($ip);
    $networkBytes = @inet_pton($network);
    if ($ipBytes === false || $networkBytes === false || strlen($ipBytes) !== strlen($networkBytes)) {
        return false;
    }
    $prefix = (int) $prefixText;
    $maximum = strlen($ipBytes) * 8;
    if ($prefix < 0 || $prefix > $maximum) {
        return false;
    }
    $wholeBytes = intdiv($prefix, 8);
    $remainingBits = $prefix % 8;
    if ($wholeBytes > 0 && substr($ipBytes, 0, $wholeBytes) !== substr($networkBytes, 0, $wholeBytes)) {
        return false;
    }
    if ($remainingBits === 0) {
        return true;
    }
    $mask = (0xFF << (8 - $remainingBits)) & 0xFF;
    return (ord($ipBytes[$wholeBytes]) & $mask) === (ord($networkBytes[$wholeBytes]) & $mask);
}

function report_client_address(array $server): string {
    $remote = (string)($server['REMOTE_ADDR'] ?? 'unknown');
    $forwarded = $server['HTTP_CF_CONNECTING_IP'] ?? null;
    if (is_string($forwarded) && filter_var($forwarded, FILTER_VALIDATE_IP) && report_ip_in_any_cidr($remote, REPORT_CLOUDFLARE_CIDRS)) return $forwarded;
    return filter_var($remote, FILTER_VALIDATE_IP) ? $remote : 'unknown';
}

<?php
declare(strict_types=1);
namespace PinProf\RecognitionReports;

final class ReportProblem extends \RuntimeException {
    public function __construct(public readonly string $errorCode, public readonly int $status) { parent::__construct($errorCode); }
}

/** The same explicit field contract ships in both apps. Unknown fields fail closed. */
final class ReportPrivacy {
    private array $contract;
    public function __construct(?string $path = null) {
        $this->contract = json_decode(file_get_contents($path ?? __DIR__ . '/recognition-report-fields-v1.json'), true, 32, JSON_THROW_ON_ERROR);
    }
    public function filter(mixed $value, bool $root = true, string $parent = '', int $depth = 0): mixed {
        if ($depth > 32) throw new ReportProblem('INVALID_DIAGNOSTICS', 400);
        if (is_object($value)) {
            $out = new \stdClass();
            foreach (get_object_vars($value) as $key => $child) {
                $allowed = in_array($key, $this->contract[$root ? 'roots' : 'fields'], true);
                // Runtime summary keys are generated by code, never device or account identifiers.
                if (!$root && $parent === 'operations' && preg_match('/^(rfdetr|dino|paddle|ocr|crop|pipeline|score_ocr|game_recognition)[a-zA-Z0-9_.-]{0,120}$/', $key)) $allowed = true;
                if ($allowed) $out->$key = $this->filter($child, false, $key, $depth + 1);
            }
            return $out;
        }
        if (is_array($value)) {
            if (count($value) > 1024) throw new ReportProblem('INVALID_DIAGNOSTICS', 400);
            return array_map(fn($v) => $this->filter($v, false, $parent, $depth + 1), $value);
        }
        if (is_string($value)) {
            // Free-form runtime error messages can contain filenames or user content.
            // Keep only a diagnostic category; full messages remain in the local payload.
            if (in_array($parent, $this->contract['error_text_fields'], true)) return self::errorCategory($value);
            foreach ($this->contract['redact_patterns'] as $pattern) {
                $value = preg_replace('~' . str_replace('~', '\\~', $pattern) . '~u', '[redacted]', $value);
            }
            return mb_substr($value, 0, 2048);
        }
        return $value;
    }
    public static function errorCategory(string $text): string {
        if ($text === '' || in_array($text, ['category:memory', 'category:gpu_compile', 'category:unsupported', 'category:shape', 'category:no_candidates', 'category:geometry', 'category:timeout', 'category:cancelled', 'category:gpu', 'category:other'], true)) return $text;
        foreach ([
            'memory' => '/out.?of.?memory|bad_alloc|allocation.*fail|insufficient.*memory/i',
            'gpu_compile' => '/compil|build.*program|shader/i',
            'unsupported' => '/unsupported|not supported|unimplemented/i',
            'shape' => '/shape|dimension|tensor.*size/i',
            'no_candidates' => '/no.*candidate|confidence.*threshold/i',
            'geometry' => '/geometry|nms|crop.*valid/i',
            'timeout' => '/timeout|timed out/i',
            'cancelled' => '/cancel/i',
            'gpu' => '/gpu|delegate|opencl|opengl|vulkan/i',
        ] as $category => $pattern) if (preg_match($pattern, $text)) return 'category:' . $category;
        return 'category:other';
    }
}

final class ReportStore {
    public const RETENTION_SECONDS = 90 * 86400;
    public const MAX_REQUEST_BYTES = 7_500_000;
    public const MAX_PHOTO_BYTES = 4_500_000;
    public function __construct(private readonly string $root, private readonly string $rateKey) {
        if (strlen($rateKey) < 32) throw new \RuntimeException('Private rate key required.');
        foreach (['', '/reports', '/rate'] as $suffix) {
            $path = $root . $suffix;
            if (!is_dir($path) && !mkdir($path, 0700, true) && !is_dir($path)) throw new \RuntimeException('Storage unavailable.');
            chmod($path, 0700);
        }
    }
    public function rateLimit(string $address, ?int $now = null): void {
        $now ??= time();
        // A daily HMAC expires with its bucket; raw IP addresses never enter report storage.
        $identity = hash_hmac('sha256', gmdate('Y-m-d', $now) . ':' . $address, $this->rateKey);
        $path = $this->root . '/rate/' . $identity . '.json';
        $lock = fopen($path, 'c+');
        if (!$lock || !flock($lock, LOCK_EX)) throw new \RuntimeException('Rate storage unavailable.');
        try {
            $state = json_decode(stream_get_contents($lock), true) ?: ['day' => 0, 'minute' => 0, 'minute_at' => $now];
            if ($now - $state['minute_at'] >= 60) { $state['minute'] = 0; $state['minute_at'] = $now; }
            if ($state['day'] >= 100 || $state['minute'] >= 12) throw new ReportProblem('RATE_LIMITED', 429);
            $state['day']++; $state['minute']++;
            rewind($lock); ftruncate($lock, 0); self::writeHandle($lock, json_encode($state, JSON_THROW_ON_ERROR));
        } finally { flock($lock, LOCK_UN); fclose($lock); }
    }
    public function submit(object $request, ?int $now = null): array {
        $now ??= time();
        $id = $request->submission_id ?? null;
        if (($request->schema_version ?? null) !== 1 || !is_string($id) || !preg_match('/^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/D', $id)) throw new ReportProblem('INVALID_REQUEST', 400);
        if (!in_array($request->platform ?? null, ['ios', 'android'], true) || !is_object($request->diagnostics ?? null)) throw new ReportProblem('INVALID_REQUEST', 400);
        $description = $request->description ?? '';
        $email = $request->email ?? '';
        if (!is_string($description) || mb_strlen($description) > 4000 || !is_string($email) || strlen($email) > 254 || ($email !== '' && !filter_var($email, FILTER_VALIDATE_EMAIL))) throw new ReportProblem('INVALID_FORM', 400);
        $diagnostics = (new ReportPrivacy())->filter($request->diagnostics);
        if (strlen(json_encode($diagnostics, JSON_THROW_ON_ERROR)) > 512_000) throw new ReportProblem('DIAGNOSTICS_TOO_LARGE', 413);
        $encodedPhoto = $request->photo_jpeg_base64 ?? null;
        if ($encodedPhoto !== null && (!is_string($encodedPhoto) || strlen($encodedPhoto) > 6_000_000)) throw new ReportProblem('PHOTO_TOO_LARGE', 413);
        $photo = $encodedPhoto === null ? null : base64_decode($encodedPhoto, true);
        if ($photo === false || ($photo !== null && (strlen($photo) === 0 || strlen($photo) > self::MAX_PHOTO_BYTES))) throw new ReportProblem('INVALID_PHOTO', 400);
        $record = ['schema_version' => 1, 'report_id' => $id, 'platform' => $request->platform,
            'description' => $description, 'email' => $email, 'diagnostics' => $diagnostics,
            'has_photo' => $photo !== null];
        $digest = hash('sha256', json_encode($record, JSON_THROW_ON_ERROR) . ($photo ?? ''));
        $lock = fopen($this->root . '/storage.lock', 'c+');
        if (!$lock || !flock($lock, LOCK_EX)) throw new \RuntimeException('Storage unavailable.');
        $staging = null;
        try {
            $destination = $this->root . '/reports/' . $id;
            if (is_dir($destination)) {
                $existing = json_decode(file_get_contents($destination . '/report.json'), true, 64, JSON_THROW_ON_ERROR);
                if (!hash_equals($existing['request_digest'], $digest)) throw new ReportProblem('SUBMISSION_CONFLICT', 409);
                return self::receipt($existing);
            }
            if ($photo !== null) $photo = self::cleanPhoto($photo);
            // Bound total private storage independently of per-client throttling.
            $used = 0;
            foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($this->root . '/reports', \FilesystemIterator::SKIP_DOTS)) as $file) $used += $file->getSize();
            if ($used > 5_000_000_000 || disk_free_space($this->root) < 250_000_000) throw new ReportProblem('STORAGE_FULL', 503);
            $record['received_at'] = gmdate('c', $now);
            $record['expires_at'] = gmdate('c', $now + self::RETENTION_SECONDS);
            $record['request_digest'] = $digest;
            $staging = $this->root . '/reports/.pending-' . bin2hex(random_bytes(12));
            if (!mkdir($staging, 0700)) throw new \RuntimeException('Storage unavailable.');
            self::writeFile($staging . '/report.json', json_encode($record, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR));
            if ($photo !== null) self::writeFile($staging . '/photo.jpg', $photo);
            if (!rename($staging, $destination)) throw new \RuntimeException('Storage commit failed.');
            $staging = null;
            return self::receipt($record);
        } finally {
            if ($staging !== null) self::removeReportDirectory($staging);
            flock($lock, LOCK_UN); fclose($lock);
        }
    }
    private static function receipt(array $record): array {
        return ['schema_version' => 1, 'report_id' => $record['report_id'], 'received_at' => $record['received_at'], 'expires_at' => $record['expires_at'], 'photo_included' => $record['has_photo']];
    }
    public static function cleanPhoto(string $bytes): string {
        $size = @getimagesizefromstring($bytes);
        if (!$size || $size[2] !== IMAGETYPE_JPEG || $size[0] > 4096 || $size[1] > 4096 || $size[0] * $size[1] > 12_600_000) throw new ReportProblem('INVALID_PHOTO', 400);
        $image = @imagecreatefromstring($bytes);
        if (!$image) throw new ReportProblem('INVALID_PHOTO', 400);
        ob_start();
        try {
            if (!imagejpeg($image, null, 90)) throw new \RuntimeException('Photo encoding failed.');
            return ob_get_contents(); // Fresh JPEG contains no source EXIF/GPS/XMP metadata.
        } finally { ob_end_clean(); unset($image); }
    }
    public function expire(?int $now = null): int {
        $now ??= time(); $count = 0;
        $lock = fopen($this->root . '/storage.lock', 'c+');
        if (!$lock || !flock($lock, LOCK_EX)) throw new \RuntimeException('Storage unavailable.');
        try {
            foreach (glob($this->root . '/reports/*', GLOB_ONLYDIR) as $directory) {
                $record = json_decode(file_get_contents($directory . '/report.json'), true);
                if (is_array($record) && strtotime($record['expires_at']) <= $now) { self::removeReportDirectory($directory); $count++; }
            }
            foreach (glob($this->root . '/reports/.pending-*', GLOB_ONLYDIR) as $directory) if (filemtime($directory) < $now - 3600) self::removeReportDirectory($directory);
            foreach (glob($this->root . '/rate/*.json') as $file) if (filemtime($file) < $now - 2 * 86400) unlink($file);
        } finally { flock($lock, LOCK_UN); fclose($lock); }
        return $count;
    }
    private static function removeReportDirectory(string $path): void {
        foreach (['report.json', 'photo.jpg'] as $name) if (is_file($path . '/' . $name)) unlink($path . '/' . $name);
        rmdir($path);
    }
    private static function writeHandle($handle, string $bytes): void {
        $offset = 0;
        while ($offset < strlen($bytes)) { $written = fwrite($handle, substr($bytes, $offset)); if (!$written) throw new \RuntimeException('Storage write failed.'); $offset += $written; }
        if (!fflush($handle) || (function_exists('fsync') && !fsync($handle))) throw new \RuntimeException('Storage sync failed.');
    }
    private static function writeFile(string $path, string $bytes): void {
        $file = fopen($path, 'xb');
        if (!$file) throw new \RuntimeException('Storage write failed.');
        chmod($path, 0600);
        try { self::writeHandle($file, $bytes); } finally { fclose($file); }
    }
}

